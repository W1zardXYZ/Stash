import { useEffect, useRef, useState } from "react";
import * as THREE from "three";
import { OrbitControls } from "three/examples/jsm/controls/OrbitControls.js";
import { RoomEnvironment } from "three/examples/jsm/environments/RoomEnvironment.js";
import { GLTFLoader } from "three/examples/jsm/loaders/GLTFLoader.js";
import { FBXLoader } from "three/examples/jsm/loaders/FBXLoader.js";
import { OBJLoader } from "three/examples/jsm/loaders/OBJLoader.js";
import { MTLLoader } from "three/examples/jsm/loaders/MTLLoader.js";
import { STLLoader } from "three/examples/jsm/loaders/STLLoader.js";
import { PLYLoader } from "three/examples/jsm/loaders/PLYLoader.js";
import { ColladaLoader } from "three/examples/jsm/loaders/ColladaLoader.js";
import { ThreeMFLoader } from "three/examples/jsm/loaders/3MFLoader.js";
import { USDZLoader } from "three/examples/jsm/loaders/USDZLoader.js";
import { RGBELoader } from "three/examples/jsm/loaders/RGBELoader.js";
import { EXRLoader } from "three/examples/jsm/loaders/EXRLoader.js";
import { TGALoader } from "three/examples/jsm/loaders/TGALoader.js";
import { Icon } from "./Icon";

export type ViewerSource =
  | { type: "model"; url: string; format: string; mtlUrl?: string }
  | { type: "pbr"; maps: Record<string, string> }
  | { type: "hdri"; url: string; format: string };

interface Props {
  source: ViewerSource;
  initialClip?: string;
  onCapture?: (dataUrl: string) => void;
}

interface Stats {
  meshes: number;
  triangles: number;
  vertices: number;
  bones: number;
  materials: number;
}

const BACKGROUNDS = [0x0b0c0f, 0x3a3d44, 0xd9dce2];

function loadTexture(url: string, srgb: boolean): Promise<THREE.Texture> {
  const lower = url.toLowerCase().split("?")[0];
  const loader: THREE.Loader<THREE.Texture | THREE.DataTexture> = lower.endsWith(".tga")
    ? new TGALoader()
    : lower.endsWith(".exr")
      ? new EXRLoader()
      : lower.endsWith(".hdr")
        ? new RGBELoader()
        : new THREE.TextureLoader();
  return new Promise((resolve, reject) => {
    (loader as any).load(
      url,
      (t: THREE.Texture) => {
        t.wrapS = t.wrapT = THREE.RepeatWrapping;
        t.colorSpace = srgb ? THREE.SRGBColorSpace : THREE.NoColorSpace;
        t.anisotropy = 8;
        resolve(t);
      },
      undefined,
      reject,
    );
  });
}

async function loadModel(src: Extract<ViewerSource, { type: "model" }>): Promise<{ object: THREE.Object3D; clips: THREE.AnimationClip[] }> {
  const f = src.format.toLowerCase();
  const url = src.url;
  const manager = new THREE.LoadingManager();
  if (f === "glb" || f === "gltf") {
    const g = await new GLTFLoader(manager).loadAsync(url);
    return { object: g.scene, clips: g.animations };
  }
  if (f === "fbx") {
    const o = await new FBXLoader(manager).loadAsync(url);
    return { object: o, clips: o.animations };
  }
  if (f === "obj") {
    const loader = new OBJLoader(manager);
    if (src.mtlUrl) {
      try {
        const mtl = await new MTLLoader(manager).loadAsync(src.mtlUrl);
        mtl.preload();
        loader.setMaterials(mtl);
      } catch {
        /* ignore missing mtl */
      }
    }
    return { object: await loader.loadAsync(url), clips: [] };
  }
  if (f === "stl" || f === "ply") {
    const geo = f === "stl" ? await new STLLoader(manager).loadAsync(url) : await new PLYLoader(manager).loadAsync(url);
    geo.computeVertexNormals();
    const mat = new THREE.MeshStandardMaterial({ color: 0xb8bcc6, roughness: 0.55, metalness: 0.05, vertexColors: geo.hasAttribute("color") });
    const mesh = new THREE.Mesh(geo, mat);
    const g = new THREE.Group();
    mesh.rotation.x = -Math.PI / 2; // STL/PLY are usually Z-up
    g.add(mesh);
    return { object: g, clips: [] };
  }
  if (f === "dae") {
    const c = await new ColladaLoader(manager).loadAsync(url);
    return { object: c!.scene, clips: (c as any)?.scene?.animations ?? [] };
  }
  if (f === "3mf") {
    const o = await new ThreeMFLoader(manager).loadAsync(url);
    o.rotation.x = -Math.PI / 2;
    return { object: o, clips: [] };
  }
  if (f === "usdz") {
    const o = await new USDZLoader(manager).loadAsync(url);
    return { object: o, clips: [] };
  }
  throw new Error(`The browser viewer can't open .${f} files – a GLB preview is generated by the server when Blender is available.`);
}

function frame(camera: THREE.PerspectiveCamera, controls: OrbitControls, object: THREE.Object3D) {
  object.updateMatrixWorld(true);
  // precise=true walks the vertices, which is what skinned meshes need for a correct bound
  const box = new THREE.Box3().setFromObject(object, true);
  if (box.isEmpty()) return;
  const size = box.getSize(new THREE.Vector3());
  const center = box.getCenter(new THREE.Vector3());
  const radius = Math.max(size.length() / 2, 1e-3);
  const vfov = THREE.MathUtils.degToRad(camera.fov);
  const hfov = 2 * Math.atan(Math.tan(vfov / 2) * camera.aspect);
  const dist = (radius / Math.sin(Math.min(vfov, hfov) / 2)) * 1.3;
  const dir = new THREE.Vector3(1, 0.55, 1.2).normalize();
  camera.position.copy(center).addScaledVector(dir, dist);
  camera.near = dist / 200;
  camera.far = dist * 200;
  camera.updateProjectionMatrix();
  controls.target.copy(center);
  controls.update();
}

function computeStats(root: THREE.Object3D): Stats {
  let meshes = 0, triangles = 0, vertices = 0, bones = 0;
  const materials = new Set<THREE.Material>();
  root.traverse((o: any) => {
    if (o.isMesh) {
      meshes++;
      const g = o.geometry as THREE.BufferGeometry;
      const pos = g.getAttribute("position");
      if (pos) vertices += pos.count;
      triangles += g.index ? g.index.count / 3 : (pos?.count ?? 0) / 3;
      (Array.isArray(o.material) ? o.material : [o.material]).forEach((m: THREE.Material) => materials.add(m));
    }
    if (o.isBone) bones++;
  });
  return { meshes, triangles: Math.round(triangles), vertices, bones, materials: materials.size };
}

export default function Viewer({ source, initialClip, onCapture }: Props) {
  const host = useRef<HTMLDivElement>(null);
  const state = useRef<any>({});
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [stats, setStats] = useState<Stats | null>(null);
  const [clips, setClips] = useState<string[]>([]);
  const [clip, setClip] = useState<string>("");
  const [playing, setPlaying] = useState(true);
  const [speed, setSpeed] = useState(1);
  const [time, setTime] = useState(0);
  const [wire, setWire] = useState(false);
  const [skeleton, setSkeleton] = useState(false);
  const [grid, setGrid] = useState(true);
  const [rotate, setRotate] = useState(false);
  const [bg, setBg] = useState(0);
  const [shape, setShape] = useState<"sphere" | "cube" | "plane">("sphere");

  // ---------- scene setup + loading
  useEffect(() => {
    const el = host.current!;
    const renderer = new THREE.WebGLRenderer({ antialias: true, preserveDrawingBuffer: true, alpha: true });
    renderer.setPixelRatio(Math.min(window.devicePixelRatio, 2));
    renderer.toneMapping = THREE.ACESFilmicToneMapping;
    renderer.toneMappingExposure = 1.0;
    renderer.outputColorSpace = THREE.SRGBColorSpace;
    el.appendChild(renderer.domElement);
    const scene = new THREE.Scene();
    const pmrem = new THREE.PMREMGenerator(renderer);
    const roomEnv = pmrem.fromScene(new RoomEnvironment(), 0.04).texture;
    scene.environment = roomEnv;
    const camera = new THREE.PerspectiveCamera(40, 1, 0.01, 1000);
    camera.position.set(2, 1.5, 2.5);
    const controls = new OrbitControls(camera, renderer.domElement);
    controls.enableDamping = true;
    controls.dampingFactor = 0.08;
    const gridHelper = new THREE.GridHelper(10, 20, 0x444851, 0x2a2d33);
    (gridHelper.material as THREE.Material).transparent = true;
    (gridHelper.material as THREE.Material).opacity = 0.6;
    scene.add(gridHelper);
    const key = new THREE.DirectionalLight(0xffffff, 1.2);
    key.position.set(3, 5, 4);
    scene.add(key);
    const clock = new THREE.Clock();
    const s = state.current;
    Object.assign(s, { renderer, scene, camera, controls, gridHelper, clock, mixer: null, actions: {}, root: null, skel: null, pmrem, roomEnv });
    (window as any).__stashViewer = s; // handy for debugging from the console

    const resize = () => {
      const w = el.clientWidth, h = el.clientHeight;
      if (!w || !h) return;
      renderer.setSize(w, h, false);
      camera.aspect = w / h;
      camera.updateProjectionMatrix();
    };
    const ro = new ResizeObserver(resize);
    ro.observe(el);
    resize();

    let raf = 0;
    let lastT = 0;
    const tick = () => {
      raf = requestAnimationFrame(tick);
      const dt = clock.getDelta();
      if (s.mixer) {
        s.mixer.update(dt);
        const a: THREE.AnimationAction | undefined = s.activeAction;
        if (a && performance.now() - lastT > 100) {
          lastT = performance.now();
          setTime(a.time);
        }
      }
      controls.update();
      renderer.render(scene, camera);
    };
    tick();

    let cancelled = false;
    setLoading(true);
    setError(null);
    (async () => {
      try {
        let root: THREE.Object3D;
        if (source.type === "model") {
          const { object, clips } = await loadModel(source);
          if (cancelled) return;
          root = object;
          root.traverse((o: any) => {
            if (o.isMesh) {
              o.castShadow = o.receiveShadow = true;
              const mats = Array.isArray(o.material) ? o.material : [o.material];
              mats.forEach((m: any) => m && (m.side = m.side ?? THREE.FrontSide));
            }
          });
          scene.add(root);
          if (clips.length) {
            const mixer = new THREE.AnimationMixer(root);
            s.mixer = mixer;
            clips.forEach((c) => (s.actions[c.name] = mixer.clipAction(c)));
            setClips(clips.map((c) => c.name));
            const first = (initialClip && clips.find((c) => c.name === initialClip || c.name.endsWith(`|${initialClip}`))) || clips[0];
            setClip(first.name);
          }
        } else if (source.type === "pbr") {
          root = new THREE.Group();
          const mat = new THREE.MeshPhysicalMaterial({ roughness: 0.6, metalness: 0 });
          const m = source.maps;
          const tasks: Promise<void>[] = [];
          const set = (ch: string, srgb: boolean, apply: (t: THREE.Texture) => void) => {
            if (m[ch]) tasks.push(loadTexture(m[ch], srgb).then(apply).catch(() => undefined));
          };
          set("base_color", true, (t) => { mat.map = t; });
          set("normal", false, (t) => { mat.normalMap = t; });
          set("roughness", false, (t) => { mat.roughnessMap = t; mat.roughness = 1; });
          set("glossiness", false, (t) => { if (!m.roughness) { mat.roughnessMap = t; mat.roughness = 1; } });
          set("metallic", false, (t) => { mat.metalnessMap = t; mat.metalness = 1; });
          set("ao", false, (t) => { mat.aoMap = t; });
          set("orm", false, (t) => { mat.aoMap = t; mat.roughnessMap = t; mat.metalnessMap = t; mat.roughness = 1; mat.metalness = 1; });
          set("height", false, (t) => { mat.displacementMap = t; mat.displacementScale = 0.04; });
          set("opacity", false, (t) => { mat.alphaMap = t; mat.transparent = true; mat.alphaTest = 0.3; });
          set("emissive", true, (t) => { mat.emissiveMap = t; mat.emissive = new THREE.Color(0xffffff); });
          await Promise.all(tasks);
          if (cancelled) return;
          mat.needsUpdate = true;
          s.pbrMaterial = mat;
          const mesh = new THREE.Mesh(new THREE.SphereGeometry(1, 128, 96), mat);
          root.add(mesh);
          s.pbrMesh = mesh;
          scene.add(root);
        } else {
          const tex = await loadTexture(source.url, !/\.(hdr|exr)$/i.test(source.url));
          if (cancelled) return;
          tex.mapping = THREE.EquirectangularReflectionMapping;
          scene.background = tex;
          scene.environment = tex;
          root = new THREE.Group();
          const chrome = new THREE.Mesh(new THREE.SphereGeometry(0.6, 64, 48), new THREE.MeshStandardMaterial({ metalness: 1, roughness: 0.02 }));
          chrome.position.x = -0.75;
          const diffuse = new THREE.Mesh(new THREE.SphereGeometry(0.6, 64, 48), new THREE.MeshStandardMaterial({ color: 0xdddddd, roughness: 0.9 }));
          diffuse.position.x = 0.75;
          root.add(chrome, diffuse);
          scene.add(root);
          gridHelper.visible = false;
          setGrid(false);
        }
        s.root = root;
        frame(camera, controls, root);
        const box = new THREE.Box3().setFromObject(root, true);
        if (!box.isEmpty()) {
          const size = box.getSize(new THREE.Vector3()).length();
          gridHelper.scale.setScalar(Math.max(size / 4, 0.01));
          gridHelper.position.y = box.min.y;
        }
        setStats(computeStats(root));
        setLoading(false);
      } catch (e: any) {
        if (!cancelled) {
          setError(e?.message || String(e));
          setLoading(false);
        }
      }
    })();

    return () => {
      cancelled = true;
      cancelAnimationFrame(raf);
      ro.disconnect();
      controls.dispose();
      scene.traverse((o: any) => {
        o.geometry?.dispose?.();
        const mats = Array.isArray(o.material) ? o.material : o.material ? [o.material] : [];
        mats.forEach((m: any) => {
          Object.values(m).forEach((v: any) => v?.isTexture && v.dispose());
          m.dispose();
        });
      });
      (scene.background as any)?.dispose?.();
      roomEnv.dispose();
      pmrem.dispose();
      renderer.dispose();
      el.removeChild(renderer.domElement);
      state.current = {};
      setClips([]);
      setClip("");
      setStats(null);
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [JSON.stringify(source)]);

  // ---------- animation selection
  useEffect(() => {
    const s = state.current;
    if (!s.mixer || !clip) return;
    Object.values(s.actions as Record<string, THREE.AnimationAction>).forEach((a) => a.stop());
    const a: THREE.AnimationAction = s.actions[clip];
    if (a) {
      a.reset().play();
      a.paused = !playing;
      s.activeAction = a;
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [clip]);

  useEffect(() => {
    const a: THREE.AnimationAction | undefined = state.current.activeAction;
    if (a) a.paused = !playing;
  }, [playing]);

  useEffect(() => {
    if (state.current.mixer) state.current.mixer.timeScale = speed;
  }, [speed]);

  // ---------- toggles
  useEffect(() => {
    state.current.root?.traverse((o: any) => {
      if (o.isMesh) (Array.isArray(o.material) ? o.material : [o.material]).forEach((m: any) => m && (m.wireframe = wire));
    });
  }, [wire, loading]);

  useEffect(() => {
    const s = state.current;
    if (!s.scene || !s.root) return;
    if (skeleton && !s.skel) {
      s.skel = new THREE.SkeletonHelper(s.root);
      s.scene.add(s.skel);
    } else if (!skeleton && s.skel) {
      s.scene.remove(s.skel);
      s.skel.dispose?.();
      s.skel = null;
    }
  }, [skeleton, loading]);

  useEffect(() => {
    if (state.current.gridHelper) state.current.gridHelper.visible = grid;
  }, [grid]);

  useEffect(() => {
    const c: OrbitControls | undefined = state.current.controls;
    if (c) {
      c.autoRotate = rotate;
      c.autoRotateSpeed = 1.5;
    }
  }, [rotate]);

  useEffect(() => {
    const s = state.current;
    if (s.scene && source.type !== "hdri") s.scene.background = new THREE.Color(BACKGROUNDS[bg]);
  }, [bg, loading, source.type]);

  useEffect(() => {
    const s = state.current;
    if (!s.pbrMesh) return;
    s.pbrMesh.geometry.dispose();
    s.pbrMesh.geometry =
      shape === "sphere" ? new THREE.SphereGeometry(1, 128, 96) : shape === "cube" ? new THREE.BoxGeometry(1.5, 1.5, 1.5, 64, 64, 64) : new THREE.PlaneGeometry(2.5, 2.5, 256, 256);
    s.pbrMesh.rotation.x = shape === "plane" ? -Math.PI / 2 : 0;
  }, [shape]);

  const capture = () => {
    const s = state.current;
    if (!s.renderer || !onCapture) return;
    const prevGrid = s.gridHelper.visible;
    const prevBg = s.scene.background;
    s.gridHelper.visible = false;
    if (source.type !== "hdri") s.scene.background = null;
    s.renderer.setClearColor(0x000000, 0);
    s.renderer.render(s.scene, s.camera);
    const src = s.renderer.domElement as HTMLCanvasElement;
    const size = Math.min(src.width, src.height);
    const c = document.createElement("canvas");
    c.width = c.height = 512;
    c.getContext("2d")!.drawImage(src, (src.width - size) / 2, (src.height - size) / 2, size, size, 0, 0, 512, 512);
    s.gridHelper.visible = prevGrid;
    s.scene.background = prevBg;
    onCapture(c.toDataURL("image/png"));
  };

  const active: THREE.AnimationAction | undefined = state.current.activeAction;
  const duration = active?.getClip().duration ?? 0;

  return (
    <div className="viewer">
      <div ref={host} style={{ position: "absolute", inset: 0 }} />
      <div className="overlay-top">
        {source.type === "model" && (
          <>
            <button className={`vbtn ${wire ? "on" : ""}`} onClick={() => setWire(!wire)} title="Wireframe"><Icon name="wire" size={14} />Wire</button>
            <button className={`vbtn ${skeleton ? "on" : ""}`} onClick={() => setSkeleton(!skeleton)} title="Show skeleton" disabled={!stats?.bones}><Icon name="bone" size={14} />Skeleton</button>
          </>
        )}
        {source.type === "pbr" && (
          <>
            {(["sphere", "cube", "plane"] as const).map((sh) => (
              <button key={sh} className={`vbtn ${shape === sh ? "on" : ""}`} onClick={() => setShape(sh)}>{sh}</button>
            ))}
          </>
        )}
        <button className={`vbtn ${grid ? "on" : ""}`} onClick={() => setGrid(!grid)} title="Grid"><Icon name="grid" size={14} /></button>
        <button className={`vbtn ${rotate ? "on" : ""}`} onClick={() => setRotate(!rotate)} title="Auto rotate"><Icon name="rotate" size={14} /></button>
        {source.type !== "hdri" && (
          <button className="vbtn" onClick={() => setBg((bg + 1) % BACKGROUNDS.length)} title="Background"><Icon name="sun" size={14} /></button>
        )}
        <button className="vbtn" onClick={() => state.current.root && frame(state.current.camera, state.current.controls, state.current.root)} title="Frame object"><Icon name="cube" size={14} />Frame</button>
        <span style={{ flex: 1 }} />
        {onCapture && (
          <button className="vbtn" onClick={capture} title="Use the current view as thumbnail"><Icon name="camera" size={14} />Set thumbnail</button>
        )}
      </div>
      {loading && <div className="loading">Loading…</div>}
      {error && <div className="err">{error}</div>}
      {stats && source.type === "model" && (
        <div className="stats">
          {stats.triangles.toLocaleString()} tris · {stats.vertices.toLocaleString()} verts · {stats.meshes} meshes · {stats.materials} mats
          {stats.bones ? ` · ${stats.bones} bones` : ""}
        </div>
      )}
      {clips.length > 0 && (
        <div className="anim-bar">
          <button className="vbtn" onClick={() => setPlaying(!playing)}><Icon name={playing ? "pause" : "play"} size={13} /></button>
          <select value={clip} onChange={(e) => setClip(e.target.value)}>
            {clips.map((c) => (
              <option key={c} value={c}>{c.split("|").pop()}</option>
            ))}
          </select>
          <input
            type="range" min={0} max={duration || 1} step={0.01} value={Math.min(time, duration)} style={{ width: 140 }}
            onChange={(e) => {
              const a: THREE.AnimationAction | undefined = state.current.activeAction;
              if (a) { a.time = parseFloat(e.target.value); setTime(a.time); }
            }}
          />
          <span className="mono" style={{ minWidth: 70 }}>{time.toFixed(2)}/{duration.toFixed(2)}s</span>
          <select value={speed} onChange={(e) => setSpeed(parseFloat(e.target.value))}>
            {[0.25, 0.5, 1, 1.5, 2].map((v) => <option key={v} value={v}>{v}×</option>)}
          </select>
          <span className="muted small">{clips.length} clip{clips.length > 1 ? "s" : ""}</span>
        </div>
      )}
    </div>
  );
}
